// Builds Pixata.Blazor.PdfViewer/wwwroot/pdfjs: src/index.js and PDF.js bundled into one minified ES module, with PDF.js's
// worker, the viewer's stylesheet, and the files PDF.js loads as it needs them (character maps, the standard fonts and image
// decoders), each with its licence
import { build } from "esbuild";
import { cpSync, copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pdfjs = join(here, "node_modules", "pdfjs-dist");
const output = join(here, "..", "..", "Pixata.Blazor.PdfViewer", "wwwroot", "pdfjs");
const { version } = JSON.parse(readFileSync(join(pdfjs, "package.json"), "utf8"));

rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });

const header = [
  "/*!",
  " * PixataPdfViewer, part of Pixata.Blazor.PdfViewer (https://github.com/MrYossu/Pixata.Utilities). Built from",
  " * build/pixata-pdfviewer; see the README there to rebuild it. Do not edit this file by hand.",
  " *",
  ` * This file includes PDF.js ${version} (https://mozilla.github.io/pdf.js/), Copyright Mozilla Foundation, used under`,
  " * the Apache License, Version 2.0, which is in pdfjs-LICENSE.txt next to this file.",
  " */"
].join("\n");

await build({
  entryPoints: [join(here, "src", "index.js")],
  outfile: join(output, "pixata-pdfviewer.js"),
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2022"],
  legalComments: "none",
  charset: "utf8",
  banner: { js: header },
  logLevel: "info"
});

// The viewer's stylesheet, minified. Its images are only for parts of PDF.js's own viewer that aren't used here, apart from
// the spinner shown while a page is drawn
await build({
  entryPoints: [join(pdfjs, "web", "pdf_viewer.css")],
  outfile: join(output, "pdf_viewer.css"),
  bundle: true,
  minify: true,
  external: ["images/*"],
  legalComments: "none",
  banner: { css: `/* PDF.js ${version} viewer styles, Copyright Mozilla Foundation, Apache License 2.0 (pdfjs-LICENSE.txt) */` },
  logLevel: "info"
});
mkdirSync(join(output, "images"));
copyFileSync(join(pdfjs, "web", "images", "loading-icon.gif"), join(output, "images", "loading-icon.gif"));

copyFileSync(join(pdfjs, "build", "pdf.worker.min.mjs"), join(output, "pdf.worker.min.mjs"));
copyFileSync(join(pdfjs, "LICENSE"), join(output, "pdfjs-LICENSE.txt"));
cpSync(join(pdfjs, "standard_fonts"), join(output, "standard_fonts"), { recursive: true });

// ASP.NET Core only serves files whose type it knows, which .bcmap isn't, so the character maps get .bin on the end, and
// src/index.js asks for them by those names. For the same reason, the CMYK colour profile (an .icc file, which PDF.js
// can't be told another name for) is left out, and PDF.js uses its own CMYK conversion instead
mkdirSync(join(output, "cmaps"));
for (const file of readdirSync(join(pdfjs, "cmaps"))) {
  copyFileSync(join(pdfjs, "cmaps", file), join(output, "cmaps", file.endsWith(".bcmap") ? `${file}.bin` : file));
}

// The image decoders and colour management, but not QuickJS, which is only for running the scripts in a PDF's forms
mkdirSync(join(output, "wasm"));
for (const file of readdirSync(join(pdfjs, "wasm")).filter(f => !/quickjs/i.test(f))) {
  copyFileSync(join(pdfjs, "wasm", file), join(output, "wasm", file));
}

writeFileSync(join(output, "README.md"), `# PDF.js ${version}

These files are built from [build/pixata-pdfviewer](https://github.com/MrYossu/Pixata.Utilities/tree/master/build/pixata-pdfviewer).
Do not edit them by hand. PDF.js is Copyright Mozilla Foundation and used under the Apache License, Version 2.0
(\`pdfjs-LICENSE.txt\`). The character maps, fonts and image decoders each have their licence next to them. The character
maps have \`.bin\` on the end of their names, as ASP.NET Core doesn't serve \`.bcmap\` files.
`);
