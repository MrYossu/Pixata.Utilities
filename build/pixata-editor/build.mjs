// Bundles src/index.js and the ProseMirror packages it uses into a single minified ES module at
// Pixata.Blazor/wwwroot/pixata-editor.js, with the licence notices of the bundled packages in its header
import { build } from "esbuild";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, "..", "..", "Pixata.Blazor", "wwwroot", "pixata-editor.js");

// Every package that ends up in the bundle, found from esbuild's metafile, with its version and licence text
function licenceHeader(inputs) {
  const packages = new Map();
  for (const path of Object.keys(inputs)) {
    const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(path);
    if (match && !packages.has(match[1])) {
      const folder = join(here, "node_modules", match[1]);
      const manifest = JSON.parse(readFileSync(join(folder, "package.json"), "utf8"));
      const licenceFile = readdirSync(folder).find(f => /^licen[cs]e/i.test(f));
      const text = licenceFile ? readFileSync(join(folder, licenceFile), "utf8").trim() : `Licence: ${manifest.license}`;
      packages.set(match[1], { version: manifest.version, licence: manifest.license, text });
    }
  }
  const names = [...packages.keys()].sort();
  const lines = [
    "PixataEditor, part of Pixata.Blazor (https://github.com/MrYossu/Pixata.Utilities). Built from build/pixata-editor; see",
    "the README there to rebuild it. Do not edit this file by hand.",
    "",
    "This file includes the following packages, which are used under their licences, reproduced below:",
    ...names.map(name => `  ${name} ${packages.get(name).version} (${packages.get(name).licence})`)
  ];
  for (const name of names) {
    lines.push("", `----- ${name} -----`, "", ...packages.get(name).text.split(/\r?\n/));
  }
  return `/*!\n${lines.map(l => ` * ${l}`.trimEnd()).join("\n")}\n */`;
}

// A first pass finds out which packages are bundled, so the header can list them
const probe = await build({
  entryPoints: [join(here, "src", "index.js")],
  bundle: true,
  write: false,
  metafile: true,
  format: "esm",
  logLevel: "silent"
});

await build({
  entryPoints: [join(here, "src", "index.js")],
  outfile: output,
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2020"],
  legalComments: "none",
  charset: "utf8",
  banner: { js: licenceHeader(probe.metafile.inputs) },
  logLevel: "info"
});
