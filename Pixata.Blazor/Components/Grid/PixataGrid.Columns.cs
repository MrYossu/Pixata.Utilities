using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Globalization;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Components;
using Microsoft.JSInterop;

namespace Pixata.Blazor.Components.Grid;

/// <summary>
/// The width of a column, as the JavaScript reports it after a resize
/// </summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public record PixataGridColumnWidth(string Key, double Width);

public partial class PixataGrid<TItem> {
  /// <summary>
  /// Lets the user resize columns by dragging the edges of their headers, or fit a column to its content by double-clicking
  /// the edge
  /// </summary>
  [Parameter]
  public bool Resizable { get; set; }

  /// <summary>
  /// Lets the user move columns by dragging their headers onto other headers
  /// </summary>
  [Parameter]
  public bool Reorderable { get; set; }

  /// <summary>
  /// Fires when the user has resized a column
  /// </summary>
  [Parameter]
  public EventCallback<PixataGridColumnResizeEventArgs<TItem>> OnColumnResize { get; set; }

  /// <summary>
  /// Fires when the user has moved a column
  /// </summary>
  [Parameter]
  public EventCallback<PixataGridColumnReorderEventArgs<TItem>> OnColumnReorder { get; set; }

  // Set once the user has resized a column. From then on, every column has a width in pixels, and the table is as wide as
  // they are, rather than stretching to fill the grid
  private bool _fixedWidths;

  // ---------- The columns, in order ----------

  // The top-level columns, with the auto-generated ones expanded in place, before ordering and hiding
  private List<PixataGridColumn<TItem>> TopColumns() {
    List<PixataGridColumn<TItem>> columns = [];
    bool generatedPlaced = false;
    foreach (PixataGridColumnBase<TItem> column in _columns) {
      switch (column) {
        case PixataGridColumn<TItem> dataColumn:
          columns.Add(dataColumn);
          break;
        case PixataGridAutoGeneratedColumns<TItem> marker when AutoGenerateColumns && !generatedPlaced:
          columns.AddRange(GeneratedColumns(marker.ColumnWidth));
          generatedPlaced = true;
          break;
      }
    }
    if (AutoGenerateColumns && !generatedPlaced) {
      columns.AddRange(GeneratedColumns(null));
    }
    return columns;
  }

  // Columns in the order the user has put them in, which starts as the order they were declared in
  private static List<PixataGridColumn<TItem>> Ordered(List<PixataGridColumn<TItem>> siblings) =>
    [.. siblings.Select((column, index) => (column, index)).OrderBy(c => c.column.RuntimeOrder ?? c.index).Select(c => c.column)];

  private static List<PixataGridColumn<TItem>> VisibleOrdered(List<PixataGridColumn<TItem>> siblings) =>
    [.. Ordered(siblings).Where(c => c.IsVisible && (!c.IsGroupColumn || LeafCount(c) > 0))];

  private static int LeafCount(PixataGridColumn<TItem> column) =>
    column.IsGroupColumn ? column.Children.Where(c => c.IsVisible).Sum(LeafCount) : 1;

  private static IEnumerable<PixataGridColumn<TItem>> Leaves(List<PixataGridColumn<TItem>> siblings) =>
    VisibleOrdered(siblings).SelectMany(c => c.IsGroupColumn ? Leaves(c.Children) : [c]);

  // The columns that have cells, in the order shown. Columns inside other columns are included, and the ones that contain
  // them aren't
  private List<PixataGridColumn<TItem>> RenderedColumns() =>
    [.. Leaves(TopColumns())];

  // Every column, including hidden ones and those that contain others
  private IEnumerable<PixataGridColumn<TItem>> AllColumns() {
    static IEnumerable<PixataGridColumn<TItem>> All(List<PixataGridColumn<TItem>> columns) =>
      columns.SelectMany(c => (IEnumerable<PixataGridColumn<TItem>>)[c, .. All(c.Children)]);
    return All(TopColumns());
  }

  private List<PixataGridColumn<TItem>> Siblings(PixataGridColumn<TItem> column) =>
    column.ParentColumn?.Children ?? TopColumns();

  // ---------- Multi-column headers ----------

  private record HeaderCell(PixataGridColumn<TItem> Column, int ColSpan, int RowSpan);

  // The header rows. A column that contains others spans them, and the others go in the rows below. A column with cells
  // spans down to the bottom row
  private List<List<HeaderCell>> HeaderRows() {
    List<PixataGridColumn<TItem>> top = VisibleOrdered(TopColumns());
    int depth = Depth(top);
    List<List<HeaderCell>> rows = [.. Enumerable.Range(0, depth).Select(_ => new List<HeaderCell>())];
    Add(top, 0);
    return rows;

    void Add(List<PixataGridColumn<TItem>> columns, int level) {
      foreach (PixataGridColumn<TItem> column in columns) {
        if (column.IsGroupColumn) {
          List<PixataGridColumn<TItem>> children = VisibleOrdered(column.Children);
          rows[level].Add(new(column, LeafCount(column), 1));
          Add(children, level + 1);
        } else {
          rows[level].Add(new(column, 1, depth - level));
        }
      }
    }
  }

  private static int Depth(List<PixataGridColumn<TItem>> columns) =>
    columns.Count == 0 ? 1 : columns.Max(c => c.IsGroupColumn ? 1 + Depth(VisibleOrdered(c.Children)) : 1);

  // ---------- Frozen columns ----------

  private static double? Pixels(string? width) {
    if (string.IsNullOrWhiteSpace(width)) {
      return null;
    }
    string number = width.Trim().EndsWith("px", StringComparison.OrdinalIgnoreCase) ? width.Trim()[..^2] : width.Trim();
    return double.TryParse(number, NumberStyles.Float, CultureInfo.InvariantCulture, out double pixels) ? pixels : null;
  }

  // Works out where the frozen columns stick. Each one sticks to the left after the frozen columns before it, and to the
  // right before the ones after it, so frozen columns at the start stay on the left, those at the end stay on the right, and
  // one in the middle stays wherever it gets pushed to. They need widths in pixels, so if any frozen column hasn't got one,
  // none are frozen
  private void LayoutColumns(List<PixataGridColumn<TItem>> leaves) {
    foreach (PixataGridColumn<TItem> column in AllColumns()) {
      column.StickyStyle = null;
      column.StickyLeft = null;
      column.StickyRight = null;
    }
    List<(PixataGridColumn<TItem> Column, double? Width)> locked = [.. leaves.Where(c => c.IsLocked).Select(c => (c, Pixels(c.CurrentWidth)))];
    if (locked.Count == 0 || locked.Any(l => l.Width is null)) {
      return;
    }
    double total = locked.Sum(l => l.Width!.Value);
    double left = 0;
    foreach ((PixataGridColumn<TItem> column, double? width) in locked) {
      SetSticky(column, left, total - left - width!.Value);
      left += width.Value;
    }
    // A column containing others sticks if they all do
    foreach (PixataGridColumn<TItem> column in AllColumns().Where(c => c.IsGroupColumn)) {
      List<PixataGridColumn<TItem>> inside = [.. Leaves(column.Children)];
      if (inside.Count > 0 && inside.All(c => c.StickyStyle is not null)) {
        SetSticky(column, inside[0].StickyLeft!.Value, inside[^1].StickyRight!.Value);
      }
    }
  }

  private static void SetSticky(PixataGridColumn<TItem> column, double left, double right) {
    column.StickyLeft = left;
    column.StickyRight = right;
    column.StickyStyle = FormattableString.Invariant($"left: {left}px; right: {right}px;");
  }

  // Once the user has resized a column, the table is as wide as its columns
  private string? TableStyle(List<PixataGridColumn<TItem>> leaves) {
    if (!_fixedWidths) {
      return null;
    }
    List<double?> widths = [.. leaves.Select(c => Pixels(c.CurrentWidth))];
    return widths.Any(w => w is null) ? null : FormattableString.Invariant($"width: {widths.Sum() + GroupLevels * 32}px;");
  }

  // ---------- Resizing ----------

  private bool CanResize(PixataGridColumn<TItem> column) =>
    Resizable && column.Resizable && !column.IsGroupColumn;

  /// <summary>
  /// Called by the JavaScript when the user has finished resizing a column, with the widths of all the columns
  /// </summary>
  [JSInvokable]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public async Task ColumnsResized(string key, PixataGridColumnWidth[] widths) {
    SetWidths(widths);
    if (AllColumns().FirstOrDefault(c => c.Key == key) is PixataGridColumn<TItem> column && OnColumnResize.HasDelegate) {
      await OnColumnResize.InvokeAsync(new(column, Pixels(column.CurrentWidth) ?? 0));
    }
    StateHasChanged();
  }

  private void SetWidths(IEnumerable<PixataGridColumnWidth> widths) {
    Dictionary<string, PixataGridColumn<TItem>> columns = AllColumns().ToDictionary(c => c.Key);
    foreach (PixataGridColumnWidth width in widths) {
      if (columns.TryGetValue(width.Key, out PixataGridColumn<TItem>? column)) {
        column.RuntimeWidth = FormattableString.Invariant($"{Math.Round(width.Width, 2)}px");
      }
    }
    _fixedWidths = true;
  }

  /// <summary>
  /// Makes the column with this <c>Id</c> as wide as its content (within its <c>MinResizableWidth</c> and
  /// <c>MaxResizableWidth</c>)
  /// </summary>
  public Task AutoFitColumn(string id) =>
    AutoFitColumns([id]);

  /// <summary>
  /// Makes the columns with these <c>Id</c>s as wide as their content
  /// </summary>
  public Task AutoFitColumns(IEnumerable<string> ids) {
    HashSet<string> wanted = [.. ids];
    return AutoFit([.. RenderedColumns().Where(c => c.Id is not null && wanted.Contains(c.Id))]);
  }

  /// <summary>
  /// Makes every column as wide as its content
  /// </summary>
  public Task AutoFitAllColumns() =>
    AutoFit(RenderedColumns());

  private async Task AutoFit(List<PixataGridColumn<TItem>> columns) {
    if (columns.Count == 0) {
      return;
    }
    try {
      _module ??= await Js.InvokeAsync<IJSObjectReference>("import", PixataBlazorScript.Path);
      PixataGridColumnWidth[]? widths = await _module.InvokeAsync<PixataGridColumnWidth[]?>("autoFitColumns", _gridId, columns.Select(c => c.Key).ToArray());
      SetWidths(widths ?? []);
      StateHasChanged();
    } catch (JSDisconnectedException) {
      // The page has gone
    }
  }

  // ---------- Reordering ----------

  private bool CanReorder(PixataGridColumn<TItem> column) =>
    Reorderable && column.Reorderable;

  // Columns can only be moved among the columns they are with, and frozen columns only among frozen ones
  private static string ReorderScope(PixataGridColumn<TItem> column) =>
    $"{column.ParentColumn?.Key}|{column.IsLocked}";

  /// <summary>
  /// Called by the JavaScript when the user drops a header on another one
  /// </summary>
  [JSInvokable]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public Task ColumnDrop(string key, string targetKey, bool before) {
    List<PixataGridColumn<TItem>> all = [.. AllColumns()];
    PixataGridColumn<TItem>? column = all.FirstOrDefault(c => c.Key == key);
    PixataGridColumn<TItem>? target = all.FirstOrDefault(c => c.Key == targetKey);
    if (column is null || target is null || column == target || column.ParentColumn != target.ParentColumn) {
      return Task.CompletedTask;
    }
    List<PixataGridColumn<TItem>> siblings = Ordered(Siblings(column));
    siblings.Remove(column);
    int index = siblings.IndexOf(target) + (before ? 0 : 1);
    return MoveTo(column, index);
  }

  // Moves a column to a position among the columns it is with (counting hidden ones), and raises OnColumnReorder
  private async Task MoveTo(PixataGridColumn<TItem> column, int index) {
    List<PixataGridColumn<TItem>> siblings = Ordered(Siblings(column));
    int oldIndex = siblings.IndexOf(column);
    siblings.Remove(column);
    index = Math.Clamp(index, 0, siblings.Count);
    siblings.Insert(index, column);
    for (int i = 0; i < siblings.Count; i++) {
      siblings[i].RuntimeOrder = i;
    }
    if (oldIndex != index && OnColumnReorder.HasDelegate) {
      await OnColumnReorder.InvokeAsync(new(column, oldIndex, index));
    }
    StateHasChanged();
  }
}

/// <summary>
/// What <c>OnColumnResize</c> is given
/// </summary>
public class PixataGridColumnResizeEventArgs<TItem>(PixataGridColumn<TItem> column, double width) {
  /// <summary>
  /// The column that was resized
  /// </summary>
  public PixataGridColumn<TItem> Column { get; } = column;

  /// <summary>
  /// Its new width, in pixels
  /// </summary>
  public double Width { get; } = width;
}

/// <summary>
/// What <c>OnColumnReorder</c> is given
/// </summary>
public class PixataGridColumnReorderEventArgs<TItem>(PixataGridColumn<TItem> column, int oldIndex, int newIndex) {
  /// <summary>
  /// The column that was moved
  /// </summary>
  public PixataGridColumn<TItem> Column { get; } = column;

  /// <summary>
  /// Where it was, among the columns it is with
  /// </summary>
  public int OldIndex { get; } = oldIndex;

  /// <summary>
  /// Where it is now
  /// </summary>
  public int NewIndex { get; } = newIndex;
}
