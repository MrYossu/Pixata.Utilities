using System;
using System.Collections.Generic;
using System.Collections.Specialized;
using System.Linq;
using Microsoft.AspNetCore.Components;
using Pixata.Extensions.Grid;

namespace Pixata.Blazor.Components.Grid;

[CascadingTypeParameter(nameof(TItem))]
public partial class PixataGrid<TItem> : IDisposable {
  /// <summary>
  /// The items to show. If you change the collection without replacing it, call <see cref="Rebind"/>, unless it implements
  /// <see cref="INotifyCollectionChanged"/> (such as <see cref="System.Collections.ObjectModel.ObservableCollection{T}"/>), in
  /// which case the grid updates itself
  /// </summary>
  [Parameter]
  public IEnumerable<TItem>? Data { get; set; }

  /// <summary>
  /// The column definitions, such as <see cref="PixataGridColumn{TItem}"/>
  /// </summary>
  [Parameter]
  public RenderFragment? GridColumns { get; set; }

  /// <summary>
  /// Adds a column for each public property of <typeparamref name="TItem"/> that holds a simple value (numbers, strings, dates,
  /// enums and so on). They go after any declared columns, unless you put a
  /// <see cref="PixataGridAutoGeneratedColumns{TItem}"/> among them. Use <c>[Display(AutoGenerateField = false)]</c> or
  /// <c>[ScaffoldColumn(false)]</c> on a property to leave it out, and <c>[Display(Order = n)]</c> to change the order
  /// </summary>
  [Parameter]
  public bool AutoGenerateColumns { get; set; }

  /// <summary>
  /// The height of the grid, as a CSS height, such as "400px". If set, the rows scroll under a fixed header. If not, the grid
  /// is as tall as its rows
  /// </summary>
  [Parameter]
  public string? Height { get; set; }

  /// <summary>
  /// The width of the grid, as a CSS width. If not set, it fills its container
  /// </summary>
  [Parameter]
  public string? Width { get; set; }

  /// <summary>
  /// A CSS class to add to the grid's outer element
  /// </summary>
  [Parameter]
  public string? Class { get; set; }

  /// <summary>
  /// The size of the grid, which sets the padding around the cells
  /// </summary>
  [Parameter]
  public PixataGridSize Size { get; set; } = PixataGridSize.Medium;

  /// <summary>
  /// What to show when there are no items. Defaults to "No records available."
  /// </summary>
  [Parameter]
  public RenderFragment? NoDataTemplate { get; set; }

  private readonly List<PixataGridColumnBase<TItem>> _columns = [];
  private List<TItem> _items = [];
  private IEnumerable<TItem>? _boundData;
  private (string? Width, List<PixataGridColumn<TItem>> Columns)? _generated;
  private bool _disposed;

  /// <summary>
  /// Re-reads the data. Call this after changing the contents of <see cref="Data"/> without replacing it
  /// </summary>
  public void Rebind() {
    ProcessData();
    StateHasChanged();
  }

  protected override void OnParametersSet() {
    if (!ReferenceEquals(Data, _boundData)) {
      Unsubscribe();
      _boundData = Data;
      if (_boundData is INotifyCollectionChanged observable) {
        observable.CollectionChanged += OnCollectionChanged;
      }
    }
    // The data is processed on every parameter change, not just when the reference changes, so a parent that changes the
    // collection in place and then re-renders sees the change. Telerik's grid needs a new reference or a Rebind() for that
    ProcessData();
  }

  private void ProcessData() =>
    _items = (_boundData ?? []).ToGridResult(new GridRequest()).Data;

  private void OnCollectionChanged(object? sender, NotifyCollectionChangedEventArgs e) =>
    _ = InvokeAsync(Rebind);

  internal void AddColumn(PixataGridColumnBase<TItem> column) =>
    _columns.Add(column);

  internal void RemoveColumn(PixataGridColumnBase<TItem> column) {
    if (_columns.Remove(column) && !_disposed) {
      StateHasChanged();
    }
  }

  // The columns to render, in order, with the auto-generated ones expanded in place
  private List<PixataGridColumn<TItem>> RenderedColumns() {
    List<PixataGridColumn<TItem>> columns = [];
    bool generatedPlaced = false;
    foreach (PixataGridColumnBase<TItem> column in _columns) {
      switch (column) {
        case PixataGridColumn<TItem> dataColumn:
          columns.Add(dataColumn);
          break;
        case PixataGridAutoGeneratedColumns<TItem> marker when AutoGenerateColumns && !generatedPlaced:
          columns.AddRange(GeneratedColumns(marker.ColumnWidth));
          generatedPlaced = true;
          break;
      }
    }
    if (AutoGenerateColumns && !generatedPlaced) {
      columns.AddRange(GeneratedColumns(null));
    }
    return [.. columns.Where(c => c.IsVisible)];
  }

  private List<PixataGridColumn<TItem>> GeneratedColumns(string? width) {
    if (_generated is null || _generated.Value.Width != width) {
      _generated = (width, [.. PixataGridAutoGeneratedColumns<TItem>.Generate(width)]);
    }
    return _generated.Value.Columns;
  }

  private string GridClass =>
    Css.Join("pixata-grid", Size switch {
      PixataGridSize.Small => "pixata-grid-sm",
      _ => "pixata-grid-md"
    }, Class);

  private string? GridStyle {
    get {
      string style = Css.Join(string.IsNullOrWhiteSpace(Height) ? null : $"height: {Height};", string.IsNullOrWhiteSpace(Width) ? null : $"width: {Width};");
      return style == "" ? null : style;
    }
  }

  private void Unsubscribe() {
    if (_boundData is INotifyCollectionChanged observable) {
      observable.CollectionChanged -= OnCollectionChanged;
    }
  }

  public void Dispose() {
    _disposed = true;
    Unsubscribe();
    GC.SuppressFinalize(this);
  }
}
